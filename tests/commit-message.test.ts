import { describe, expect, it } from "vitest";
import { isAcceptedCommitMessage } from "../scripts/commit-message.ts";

describe("commit message check", () => {
  it.each([
    "feat: add errand brief schema",
    "fix(calls): retry once per provider",
    "refactor(bookings)!: rename commit grant",
    "docs: explain model profiles\n\nLonger body text.",
  ])("accepts Conventional Commits: %s", (message) => {
    expect(isAcceptedCommitMessage(message)).toBe(true);
  });

  it.each([
    "Merge branch 'feat/repo-foundation-01-toolchain'",
    'Revert "feat: add errand brief schema"',
    "fixup! feat: add errand brief schema",
    "squash! feat: add errand brief schema",
    "amend! feat: add errand brief schema",
  ])("accepts messages generated by git: %s", (message) => {
    expect(isAcceptedCommitMessage(message)).toBe(true);
  });

  it.each([
    "added stuff",
    "Feat: capitalized type",
    "feat:missing space",
    "feat(Scope): uppercase scope",
    "wip: unknown type",
    "",
  ])("rejects: %j", (message) => {
    expect(isAcceptedCommitMessage(message)).toBe(false);
  });
});
